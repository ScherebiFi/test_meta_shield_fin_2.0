_ENGINES: dict[str, Engine] = {}
_ENGINE_LOCK = Lock()


class Record(Mapping[str, Any]):
    def __init__(self, row: Row[Any]):
        self._data = row._mapping

    def __getitem__(self, key: str | int) -> Any:
        if isinstance(key, int):
            return self._data[list(self._data.keys())[key]]
        return self._data[key]

    def __iter__(self) -> Iterator[str]:
        return iter(self._data)

    def __len__(self) -> int:
        return len(self._data)


class QueryResult:
    def __init__(self, result: Any):
        self._result = result
        self.rowcount = result.rowcount

    def fetchone(self) -> Record | None:
        row = self._result.fetchone()
        return Record(row) if row is not None else None

    def fetchall(self) -> list[Record]:
        return [Record(row) for row in self._result.fetchall()]


class DatabaseConnection:
    def __init__(self, connection: Connection):
        self._connection = connection

    def execute(
        self, statement: str, parameters: tuple[Any, ...] | list[Any] | Mapping[str, Any] = ()
    ) -> QueryResult:
        if isinstance(parameters, Mapping):
            bound = dict(parameters)
        else:
            values = list(parameters)
            index = 0

            def replace_parameter(_: re.Match[str]) -> str:
                nonlocal index
                name = f"p{index}"
                index += 1
                return f":{name}"

            statement = re.sub(r"\?", replace_parameter, statement)
            bound = {f"p{i}": value for i, value in enumerate(values)}
        if self._connection.dialect.name == "postgresql":
            statement = statement.replace(
                "INTEGER PRIMARY KEY AUTOINCREMENT",
                "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            )
        return QueryResult(self._connection.execute(text(statement), bound))

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)


def _engine(database_url: str) -> Engine:
    if database_url.startswith("postgres://"):
        database_url = "postgresql+psycopg://" + database_url.removeprefix("postgres://")
    elif database_url.startswith("postgresql://"):
        database_url = "postgresql+psycopg://" + database_url.removeprefix("postgresql://")
    with _ENGINE_LOCK:
        engine = _ENGINES.get(database_url)
        if engine is None:
            if database_url.startswith("sqlite:///"):
                Path(database_url.removeprefix("sqlite:///")).parent.mkdir(parents=True, exist_ok=True)
            engine = create_engine(
                database_url,
                pool_pre_ping=True,
                pool_size=5,
                max_overflow=10 if database_url.startswith("postgresql+") else 0,
            )
            _ENGINES[database_url] = engine
        return engine


def close_engines() -> None:
    with _ENGINE_LOCK:
        engines = list(_ENGINES.values())
        _ENGINES.clear()
    for engine in engines:
        engine.dispose()


def _database_url() -> str:
    return os.getenv("DATABASE_URL") or f"sqlite:///{DB_PATH}"


@contextmanager
def connect() -> Iterator[DatabaseConnection]:
    engine = _engine(_database_url())
    connection = engine.connect()
    if connection.dialect.name == "sqlite":
        connection.exec_driver_sql("PRAGMA foreign_keys = ON")
        connection.exec_driver_sql("PRAGMA journal_mode = WAL")
        connection.commit()
    transaction = connection.begin()
    db = DatabaseConnection(connection)
    try:
        yield db
        transaction.commit()
    except Exception:
        transaction.rollback()
        raise
    finally:
        connection.close()


